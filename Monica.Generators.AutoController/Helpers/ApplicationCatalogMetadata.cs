using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Monica.Generators.AutoController.Constants;
using Monica.Generators.AutoController.Diagnostics;
using Monica.Generators.AutoController.Models;

namespace Monica.Generators.AutoController.Helpers;

/// <summary>Serializes ownership as strings so catalog assemblies cannot introduce implementation dependencies.</summary>
internal static class ApplicationCatalogMetadata
{
    internal const string EXPORT_KEY = "Monica.ApplicationModel.Export.v1";
    internal const string CATALOG_KEY = "Monica.ApplicationModel.Catalog.v1";
    internal const string INPUT_SUFFIX = ".monica-application.xml";

    internal static IEnumerable<string> ReadAttributes(IAssemblySymbol assembly, string key) => assembly.GetAttributes()
        .Where(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyMetadataAttribute" &&
            attribute.ConstructorArguments.Length == 2 && (string?)attribute.ConstructorArguments[0].Value == key)
        .Select(static attribute => (string)attribute.ConstructorArguments[1].Value!);

    internal static string GenerateSource(ApplicationHostModel model, string key) =>
        "// <auto-generated />\n#nullable enable\n" +
        "[assembly: global::System.Reflection.AssemblyMetadata(" + SymbolDisplay.FormatLiteral(key, true) + ", " +
        SymbolDisplay.FormatLiteral(Serialize(model), true) + ")]\n";

    private static string Serialize(ApplicationHostModel model) => new XElement("ApplicationCatalog",
        new XAttribute("Schema", "1"),
        new XElement("Assemblies", model.Assemblies.OrderBy(static assembly => assembly.AssemblyName, StringComparer.Ordinal)
            .Select(static assembly => new XElement("Assembly", new XAttribute("Name", assembly.AssemblyName),
                new XAttribute("Domain", assembly.DomainId),
                assembly.RoleId is null ? null : new XAttribute("Role", assembly.RoleId),
                assembly.WorkloadOwner is null ? null : new XAttribute("WorkloadOwner", assembly.WorkloadOwner)))),
        new XElement("Operations", model.Operations.Where(static operation => operation.Published)
            .OrderBy(static operation => operation.RequestTypeName, StringComparer.Ordinal)
            .Select(static operation => new XElement("Operation",
                new XAttribute("Request", operation.RequestTypeName),
                new XAttribute("Handler", operation.HandlerTypeName),
                new XAttribute("HandlerAssembly", operation.HandlerAssemblyName),
                new XAttribute("Domain", operation.DomainId), new XAttribute("Role", operation.RoleId),
                operation.RequiredRole is null ? null : new XAttribute("RequiredRole", operation.RequiredRole),
                new XAttribute("Result", operation.Endpoint!.ResultTypeName),
                new XAttribute("Method", operation.Endpoint.HttpMethod),
                new XAttribute("Route", operation.Endpoint.CompleteRoute),
                new XAttribute("Binding", operation.Endpoint.Binding),
                operation.Tags.Select(static tag => new XElement("Tag", tag)))))).ToString(SaveOptions.DisableFormatting);

    internal static AnalysisSnapshot<ApplicationHostModel> Read(Compilation compilation, IEnumerable<string> payloads,
        bool validateCompleteness)
    {
        var diagnostics = new List<DiagnosticSnapshot>();
        var assemblies = new List<ApplicationAssemblyModel>();
        var operations = new List<ApplicationOperationModel>();
        Dictionary<string, INamedTypeSymbol>? requestTypes = null;
        foreach (var payload in payloads)
        {
            try
            {
                var document = XElement.Parse(payload);
                if (document.Name != "ApplicationCatalog" || (string?)document.Attribute("Schema") != "1")
                    throw new InvalidOperationException("Unsupported application catalog schema.");
                foreach (var item in document.Element("Assemblies")?.Elements("Assembly") ?? [])
                    assemblies.Add(new ApplicationAssemblyModel(Required(item, "Name"), Required(item, "Domain"),
                        Optional(item, "Role"), Optional(item, "WorkloadOwner")));
                foreach (var item in document.Element("Operations")?.Elements("Operation") ?? [])
                {
                    var requestName = Required(item, "Request");
                    // Nested requests use C# display names in the export; resolve against symbols rather than guessing '+' separators.
                    requestTypes ??= compilation.SourceModule.ReferencedAssemblySymbols.Append(compilation.Assembly)
                        .SelectMany(static assembly => HostGenerationReader.Types(assembly.GlobalNamespace))
                        .GroupBy(static type => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), StringComparer.Ordinal)
                        .Where(static group => group.Count() == 1).ToDictionary(static group => group.Key, static group => group.Single(), StringComparer.Ordinal);
                    if (!requestTypes.TryGetValue(requestName, out var request) ||
                        !compilation.IsSymbolAccessibleWithin(request, compilation.Assembly) || !EndpointModelFactory.IsPublishedRequest(request) ||
                        EndpointModelFactory.GetEndpointAttribute(request) is not { } endpointAttribute)
                        throw new InvalidOperationException($"Catalog request '{requestName}' is not an accessible published contract in this compilation.");
                    var endpointAnalysis = EndpointModelFactory.Create(request, endpointAttribute, compilation.Assembly,
                        Location.None, publishedOnly: true);
                    diagnostics.AddRange(endpointAnalysis.Diagnostics);
                    if (endpointAnalysis.Value is not { } endpoint) continue;
                    var role = Required(item, "Role");
                    var requiredRole = Optional(item, "RequiredRole");
                    var requirement = request.GetAttributes().FirstOrDefault(attribute =>
                        attribute.AttributeClass?.ToDisplayString() == GeneratorConstants.RUN_ON_ROLE_ATTRIBUTE);
                    if ((string?)requirement?.ConstructorArguments.FirstOrDefault().Value != requiredRole ||
                        requiredRole is not null && requiredRole != role)
                        throw new InvalidOperationException($"Catalog execution ownership for '{requestName}' differs from its current contract. Rebuild the producing role and catalog.");
                    if (Required(item, "Result") != endpoint.ResultTypeName || Required(item, "Method") != endpoint.HttpMethod ||
                        Required(item, "Route") != endpoint.CompleteRoute || Required(item, "Binding") != endpoint.Binding)
                        throw new InvalidOperationException($"Catalog endpoint metadata for '{requestName}' is stale. Rebuild the producing role and catalog.");
                    operations.Add(new ApplicationOperationModel(requestName, Required(item, "Handler"), Required(item, "HandlerAssembly"),
                        Required(item, "Domain"), role, requiredRole, endpoint, published: true,
                        item.Elements("Tag").Select(static tag => tag.Value).ToImmutableArray()));
                }
            }
            catch (Exception exception) when (exception is InvalidOperationException or System.Xml.XmlException or ArgumentException)
            {
                Invalid(exception.Message);
            }
        }

        foreach (var group in assemblies.GroupBy(static assembly => assembly.AssemblyName, StringComparer.Ordinal).Where(static group => group.Count() > 1))
            Invalid($"Assembly '{group.Key}' appears more than once in the product catalog inputs.");
        foreach (var group in assemblies.GroupBy(static assembly => assembly.RoleId is null ? "domain:" + assembly.DomainId : "role:" + assembly.RoleId,
                     StringComparer.Ordinal).Where(static group => group.Count() > 1))
            Invalid($"Ownership '{group.Key}' is declared by multiple catalog inputs.");
        var domains = new HashSet<string>(assemblies.Where(static assembly => assembly.RoleId is null).Select(static assembly => assembly.DomainId), StringComparer.Ordinal);
        foreach (var role in assemblies.Where(static assembly => assembly.RoleId is not null))
            if (!domains.Contains(role.DomainId))
                diagnostics.Add(DiagnosticSnapshot.Create(DiagnosticDescriptors.UndefinedApplicationDomain, Location.None, role.RoleId, role.DomainId));
        foreach (var operation in operations)
            if (!assemblies.Any(assembly => assembly.AssemblyName == operation.HandlerAssemblyName && assembly.RoleId == operation.RoleId && assembly.DomainId == operation.DomainId))
                Invalid($"Operation '{operation.RequestTypeName}' does not match an exported role assembly.");
        foreach (var duplicate in operations.GroupBy(static operation => operation.RequestTypeName, StringComparer.Ordinal).Where(static group => group.Count() > 1))
            diagnostics.Add(DiagnosticSnapshot.Create(DiagnosticDescriptors.DuplicateApplicationHandler, Location.None, duplicate.Key,
                string.Join(", ", duplicate.Select(static operation => operation.HandlerTypeName))));
        if (validateCompleteness)
            ApplicationHostModelReader.ValidateApiCompleteness(compilation.SourceModule.ReferencedAssemblySymbols.Append(compilation.Assembly), operations, diagnostics, Location.None);
        ApplicationHostModelReader.ValidateDuplicates(operations, diagnostics, Location.None);
        return new AnalysisSnapshot<ApplicationHostModel>(diagnostics.Any(static diagnostic => diagnostic.ToDiagnostic().Severity == DiagnosticSeverity.Error)
            ? null : new ApplicationHostModel(assemblies.OrderBy(static assembly => assembly.AssemblyName, StringComparer.Ordinal).ToImmutableArray(),
                operations.OrderBy(static operation => operation.RequestTypeName, StringComparer.Ordinal).ToImmutableArray(), []), diagnostics);

        void Invalid(string message) => diagnostics.Add(DiagnosticSnapshot.Create(DiagnosticDescriptors.InvalidApplicationCatalog, Location.None, message));
    }

    private static string Required(XElement element, string name) => Optional(element, name) ??
        throw new InvalidOperationException($"Catalog element '{element.Name}' requires '{name}'.");

    private static string? Optional(XElement element, string name)
    {
        var value = (string?)element.Attribute(name);
        if (value is not null && (string.IsNullOrWhiteSpace(value) || value != value.Trim()))
            throw new InvalidOperationException($"Catalog field '{name}' must be a nonempty identifier without surrounding whitespace.");
        return value;
    }
}
